#: The strings a copycat needs, and the only ones scrubbed from what
#: survives: CVELab's own canary, whatever the effect predicate matches on,
#: and the values the lab recorded for the inputs its single-instance script
#: asks the operator for -- the route its adapter serves, the account its
#: setup created. The model's prose quotes all three, in sections that are
#: otherwise a description: the canary appears in REPORT.md's impact, and the
#: route in its fidelity note, where it survived the first cut of this.
#:
#: Eight characters, because a short needle matches words -- except a path,
#: which starts with a slash and so matches nothing else, and which is short
#: far more often than not: `/render` is seven.
#: A canary in the spellings the archive actually holds: `CVELAB-<hex>`,
#: `CVELAB-EXEC-<hex>`, `CVELAB-<hex>-42`. Only the upper-case family, and
#: only with a run of hex in it: a lower-case `cvelab-` pattern would eat
#: `cvelab-setup.json` and CVELAB_MANUAL_ACTION, neither of them secret and
#: both of them in these documents. A marker spelled some other way reaches
#: the scrub as a needle taken from the predicate that names it.
_CANARY = re.compile(r"CVELAB-(?:[A-Z]+-)*[0-9a-f]{8,}")
_MIN_NEEDLE = 8
_MIN_PATH_NEEDLE = 4

#: What marks a needle as something no sentence could have meant: a path, a
#: payload, a credential pair, a header value. A needle of letters and digits
