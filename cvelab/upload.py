class UploadError(RuntimeError):
    """The control plane refused the run, or could not be reached.

    `failures` lists the checks a refused validated run did not pass (HTTP
    422), and `retry_after` is the wait, in seconds, a rate limit asked for
    (HTTP 429). Both are empty otherwise.
    """

    def __init__(self, message: str, *, failures: list[str] | None = None,
                 retry_after: int | None = None) -> None:
        super().__init__(message)
        self.failures = failures or []
        self.retry_after = retry_after


def endpoint() -> str:
    return os.getenv(ENDPOINT_VARIABLE, DEFAULT_ENDPOINT).rstrip("/")


def insecure_endpoint() -> str | None:
    """Why the endpoint may not carry a token, or None when it may.

    The token travels in a header and the exploit in the body, so plain
    HTTP is refused except to this machine, where a control plane under
    `wrangler dev` listens on http://localhost:8787.
    """
    url = endpoint()
    scheme = urlparse(url).scheme.lower()
    if scheme == "https" or (scheme == "http" and is_loopback(url)):
        return None
    return (
        f"{ENDPOINT_VARIABLE} is {url}; uploads need https://, "
        "or http:// to localhost, 127.0.0.1 or [::1]"
    )


def find_token() -> str | None:
    """The environment first, then the file; neither is an error."""
    token = (os.getenv(TOKEN_VARIABLE) or "").strip()
    if token:
        return token
    try:
        token = TOKEN_FILE.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    return token or None


def strip_local_paths(text: str, lab_dir: Path) -> str:
    """Replace this machine's paths with ones that say nothing about it.

    A lab's documents quote the paths it ran from: Docker and Compose errors
    name the lab directory, tool output names the home directory. In the
    shared database that shows the filer's user name and how their disk is
    laid out. The lab directory becomes its own name, which is the CVE, and
    anything else under the home directory becomes `~`.
    """
    replacements: dict[str, str] = {}
    for root in (lab_dir, lab_dir.resolve()):
        if str(root) not in ("", "/", "."):
            replacements[str(root)] = lab_dir.name
    home = str(Path.home())
    if home not in ("", "/"):
        replacements.setdefault(home, "~")
    # Longest first, so the lab directory wins over the home directory it
    # sits under.
    for old in sorted(replacements, key=len, reverse=True):
        new = replacements[old]
        text = text.replace(old, new)
        # A Windows path inside JSON text has its backslashes doubled.
        escaped = json.dumps(old)[1:-1]
        if escaped != old:
            text = text.replace(escaped, json.dumps(new)[1:-1])
    return text


def read_document(path: Path, lab_dir: Path | None = None) -> dict | None:
    """One file, redacted, trimmed if it is enormous, or None if absent."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None
    # Files were written through write_text and are already redacted. Doing it
    # again costs nothing and covers anything assembled another way.
    text = redact(text)
    text = strip_local_paths(text, lab_dir if lab_dir is not None else path.parent.parent)
    encoded = text.encode("utf-8")
    truncated = len(encoded) > MAX_DOCUMENT_BYTES
    if truncated:
        # A JSON document cut at the end no longer parses, so it is shortened
        # from the inside instead. Anything else, or JSON that will not fit
        # that way, is cut on a character boundary, not a byte one.
        trimmed = fit_json(text, MAX_DOCUMENT_BYTES) if path.suffix == ".json" else None
        text = trimmed or encoded[:MAX_DOCUMENT_BYTES].decode("utf-8", "ignore")
    return {"name": path.name, "text": text, "truncated": truncated}


#: fit_json() never cuts a string below this, so the short fields a reader or
#: the share gate looks at (cve, status, lab_type, proof checks) stay whole.
MIN_STRING_CAP = 1024


def fit_json(text: str, limit: int) -> str | None:
    """A JSON document shortened inside its strings, so that it still parses.

    Every string longer than one cap keeps its head and says how much it
    lost, and the cap is the highest that brings the document under `limit`.
    In practice one field is enormous, the validator's raw output, and that
    is the one that gives way. None when the text is not JSON, or when even
    MIN_STRING_CAP leaves it too large.
    """
    try:
        value = json.loads(text)
    except ValueError:
        return None
    longest = max(_string_lengths(value), default=0)
    best, low, high = None, MIN_STRING_CAP, longest
    while low <= high:
        cap = (low + high) // 2
        candidate = json.dumps(_cap_strings(value, cap), indent=2)
        if len(candidate.encode("utf-8")) <= limit:
            best, low = candidate, cap + 1
        else:
            high = cap - 1
    return best


def _string_lengths(value: object) -> Iterator[int]:
    if isinstance(value, str):
        yield len(value)
    elif isinstance(value, dict):
        for item in value.values():
            yield from _string_lengths(item)
    elif isinstance(value, list):
        for item in value:
            yield from _string_lengths(item)


def _cap_strings(value: object, cap: int) -> object:
    if isinstance(value, str):
        if len(value) <= cap:
            return value
        lost = len(value[cap:].encode("utf-8"))
        shortened = f"{value[:cap]}... [{lost:,} bytes trimmed]"
        # Just over the cap, the note would be longer than what it replaces.
        return shortened if len(shortened) < len(value) else value
    if isinstance(value, dict):
        return {key: _cap_strings(item, cap) for key, item in value.items()}
    if isinstance(value, list):
        return [_cap_strings(item, cap) for item in value]
    return value


def _needles(documents: list[dict]) -> list[tuple[str, bool]]:
    """The attack's own strings, read out of the payload before it is cut.

    Taken from the documents rather than from the lab, because this runs on
    what is about to be sent. The predicate's match string and the lab's
    recorded input values are what make a surviving sentence a recipe.

    Each one comes back with whether it may be replaced anywhere it appears.
    A needle that could be an English word may not: `{"header": {"name":
    "Location"}}` is a predicate, and replacing "Location" wherever it occurs
    turned REPORT.md's own finding into "`<withheld by --no-poc>` header
    percent-encodes the backslash" -- the sentence saying what was found
    stopped naming the header that leaked. `accepted` and
    `UnidentifiedImageError` are two more, from `body_contains`. Those are
    replaced only where a string IS the needle, which is a value rather than
    a sentence about one. A needle carrying a slash, a backslash, a brace or
    a space cannot be mistaken for a word and is replaced anywhere.

    `effect_predicate.header.name` is not taken at all: a header name is
    never the secret, and it is the one part of that predicate a reader needs
    to understand the finding.

    Percent-decoding is the one normalisation. A needle arrived as
    `%5C@attacker` while the observation that survived held the decoded
    `http://localhost\\@attacker`, so the encoded form matched nothing;
    `unquote` of a needle with no escape returns it unchanged, so this adds
    needles only where there was an encoding to undo. No other normalisation
    is attempted, and a needle that reaches a document in some third spelling
    is a miss -- which is why the records it comes from are withheld whole
    rather than scrubbed.
    """
    found: list[str] = []
    for document in documents:
        if not document["name"].endswith(".json"):
            continue
        try:
            held = json.loads(document["text"])
        except ValueError:
            continue
        if not isinstance(held, dict):
            continue
        contract = held.get("proof_contract")
        if isinstance(contract, dict):
            found.extend(_predicate_strings(contract.get("effect_predicate")))
        record = held.get("manual_poc_field")
        if isinstance(record, dict):
            values = record.get("lab_values")
            if isinstance(values, dict):
                found.extend(_strings(values))
            for key in ("spec", "attempted_spec"):
                spec = record.get(key)
                if isinstance(spec, dict):
                    for check in spec.get("checks") or []:
                        if isinstance(check, dict):
                            found.extend(_predicate_strings(check.get("expect")))
    wanted: set[str] = set()
    for value in found:
        spellings = {value, unquote(value)}
        # And the marker inside it. The needle for one archived lab was the
        # whole traversal, `..\..\cvelab-canary.txt`, while three allowed
        # fields mentioned the file by name alone -- and the canary pattern
        # below matches `CVELAB-<hex>` rather than that spelling. Measured
        # across the archive, every marker a predicate names is prefixed
        # `cvelab`: `CVELAB-<hex>`, `CVELAB-EXEC-<hex>`, `cvelab-canary.txt`,
        # `cvelab-admin-scope-token-0002`. They are taken from the predicate
        # rather than matched by a pattern over the document, so that
        # CVELAB_MANUAL_ACTION and `cvelab-setup.json` -- neither of them
        # secret, both of them in these documents -- are left alone.
        spellings.update(_MARKER.findall(value))
        for spelling in spellings:
            floor = _MIN_PATH_NEEDLE if spelling.startswith("/") else _MIN_NEEDLE
            if len(spelling) >= floor:
                wanted.add(spelling)
    # Longest first, so a needle that contains another is replaced whole.
    return [
        (value, bool(_NOT_A_WORD.search(value)))
        for value in sorted(wanted, key=len, reverse=True)
    ]


def _predicate_strings(expect: object) -> Iterator[str]:
    """An expectation's match strings, without the header name it reads."""
    if not isinstance(expect, dict):
        yield from _strings(expect)
        return
    for key, value in expect.items():
        if key == "header" and isinstance(value, dict):
            yield from _strings({k: v for k, v in value.items() if k != "name"})
        elif key == "header" and isinstance(value, str):
            continue
        else:
            yield from _strings(value)


def _strings(value: object) -> Iterator[str]:
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from _strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from _strings(item)


def _scrubbed(text: str, needles: list[tuple[str, bool]]) -> str:
    """One string with the attack's own strings taken out of it.

    The canary goes first, before any needle can take a bite out of one: two
    archived predicates are the bare prefix `CVELAB-`, and replacing that
    first would leave the hex that follows it standing on its own.
    """
    text = _CANARY.sub("<canary withheld by --no-poc>", text)
    for needle, anywhere in needles:
        if anywhere:
            text = text.replace(needle, _WITHHELD)
        elif text.strip() == needle:
            text = _WITHHELD
    return text


def _scrubbed_value(value: object, needles: list[tuple[str, bool]]) -> object:
    """The same, walking a parsed document rather than its text.

    This is the fix for a leak, and the leak was this: the scrub ran over the
    re-serialized JSON while the needles are decoded Python strings, so a
    needle holding a quote, a backslash, a newline or a non-ASCII character
    could not match -- `json.dumps` had escaped it, and `ensure_ascii=True`
    widened the gap. Measured on one archived lab, a `--no-poc` report.json
    still carried `{"name": "..\\..\\cvelab-canary.txt"}`, the traversal
    filename, which is the payload: `needle in decoded` was true while
    `needle in text` was false. 30 needles across the archive carry such a
    character, mostly body_regex predicates. The markdown documents are
    scrubbed as text, where there is no escaping to go wrong.
    """
    if isinstance(value, str):
        return _scrubbed(value, needles)
    if isinstance(value, dict):
        return {key: _scrubbed_value(item, needles) for key, item in value.items()}
    if isinstance(value, list):
        return [_scrubbed_value(item, needles) for item in value]
    return value


def _reaches(route: list[str], path: str) -> bool:
    """Whether a path names exactly this route, `*` matching any one key.

    `strict=True` although the length is already checked: the two have to be
    the same length for this answer to mean anything, and if that guard is
    ever moved or dropped, a silent zip would compare the prefix and say yes
    -- which in an allowlist means a field nobody named travelling. Raising
    is the right failure here; truncating is the one this whole pass exists
    to prevent.
    """
    wanted = path.split(".")
    return len(wanted) == len(route) and all(
        name in ("*", here) for name, here in zip(wanted, route, strict=True)
    )


def _passes_through(route: list[str], path: str) -> bool:
    """Whether a path names something under this route.

    `strict=False`, and here that is the question being asked: the guard
    above requires the path to be longer than the route, so the zip is meant
    to stop at the route's end and compare the prefix. `strict=True` would
    raise on every call.
    """
    wanted = path.split(".")
    return len(wanted) > len(route) and all(
        name in ("*", here) for name, here in zip(wanted, route, strict=False)
    )


def _allowed(
    value: object, paths: tuple[str, ...], route: list[str] | None = None
) -> tuple[object, list[str]]:
    """One JSON object cut down to the paths named, and what was cut.

    A path names a key or a dotted route to one, and naming a key keeps its
    whole subtree. Anything not named is dropped and reported, which is what
    makes a field nobody has classified yet travel nowhere.

    A `*` segment stands for any one key, which is how a dict keyed by
    something a run invented is filtered: `manual_poc_checks` is keyed
    `<build>_<action>`, and each entry carried the whole of what the manual
    runner printed -- status, every response header and the full body of both
    builds. That is the material `validation.*.observations` is dropped for,
    allowed wholesale one key away from it.
    """
    route = route or []
    if not isinstance(value, dict):
        return value, []
    kept: dict[str, object] = {}
    withheld: list[str] = []
    for key, item in value.items():
        here = [*route, key]
        if any(_reaches(here, path) for path in paths):
            kept[key] = item
            continue
        if isinstance(item, dict) and any(_passes_through(here, path) for path in paths):
            inner, lost = _allowed(item, paths, here)
            if inner:
                kept[key] = inner
            withheld.extend(lost)
            continue
        withheld.append(".".join(here))
    return kept, withheld


#: The heading a withheld section keeps, so the document says where the cut
#: is rather than closing the gap over it.
_SECTION_WITHHELD = (
    "_Withheld by `--no-poc`: this section is how the effect was produced "
    "rather than what was found._"
)


def _described_markdown(text: str, headings: tuple[str, ...]) -> tuple[str, list[str]]:
    """A document with the body of every unnamed section taken out."""
    blocks = re.split(r"\n(?=## )", text)
    out: list[str] = []
    withheld: list[str] = []
    for block in blocks:
        first, _, _ = block.partition("\n")
        if not first.startswith("## "):
            out.append(block)
            continue
        heading = first[3:].strip()
        if heading in headings:
            out.append(block)
            continue
        withheld.append(heading)
        out.append(f"{first}\n\n{_SECTION_WITHHELD}\n")
    return "\n".join(out), withheld


def withhold_the_attack(documents: list[dict]) -> list[dict]:
    """Every document a `--no-poc` upload still files, with the attack out.

    The documents are rewritten in the payload and the lab on disk is never
    touched: what the operator keeps is the whole lab, and what this decides
    is only what leaves the machine.

    A name with no entry in DESCRIBED_ONLY is dropped rather than guessed at.
    Nothing in ALWAYS is in that position today; the next thing added to it
    will be, until someone classifies it.
    """
    needles = _needles(documents)
    kept: list[dict] = []
    for document in documents:
        allowed = DESCRIBED_ONLY.get(document["name"])
        if allowed is None:
            continue
        if document["name"].endswith(".json"):
            try:
                held = json.loads(document["text"])
            except ValueError:
                # Not the document it claims to be. The gate refuses an
                # EVIDENCE.json that is not an object, and sending it
                # unredacted to be refused would be the one outcome worse
                # than sending nothing.
                continue
            held, withheld = _allowed(held, allowed)
            # Scrubbed parsed and then serialized, so that a needle holding a
            # character json.dumps escapes is still found. The note is added
            # after, so nothing in it can be replaced.
            held = _scrubbed_value(held, needles)
            held["withheld_by_no_poc"] = {
                "fields": withheld,
                "why": NO_POC_NOTE,
            }
            text = json.dumps(held, indent=2, ensure_ascii=True) + "\n"
        else:
            text, withheld = _described_markdown(document["text"], allowed)
            if withheld:
                text += (
                    "\n## Withheld\n\n"
                    + "\n".join(f"- `{name}`" for name in withheld)
                    + f"\n\n{NO_POC_NOTE}\n"
                )
        kept.append({
            "name": document["name"],
            # The JSON documents were scrubbed as values above; a document is
            # scrubbed as text only where it is text.
            "text": text if document["name"].endswith(".json")
                    else _scrubbed(text, needles),
            "truncated": document["truncated"],
        })
    return kept


def _plan(lab_dir: Path) -> dict:
    """plan.json holds what was actually resolved, not what was asked for."""
    try:
        return json.loads((lab_dir / "plan.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def collect(
    lab_dir: Path,
    result: dict,
    *,
    provider: str | None,
    model: str | None,
    include_poc: bool,
) -> dict:
    """Build the payload, reading only from the allowlist above."""
    artifacts = lab_dir / "artifacts"
    names = ALWAYS if include_poc else tuple(n for n in ALWAYS if n not in EXPLOIT)
    documents = [doc for doc in (read_document(artifacts / n, lab_dir) for n in names) if doc]
    if not include_poc:
        # Before the trim, not after: the fields this takes out are the
        # longest in the payload -- the validator's own transcript is one of
        # them -- so a document that would have been cut for size usually
        # fits once the attack is out of it, and `truncated` then says
        # something true about what was sent.
        documents = withhold_the_attack(documents)
    documents, dropped = fit_payload(documents)

    plan = _plan(lab_dir)
    revisions = plan.get("revisions") or {}
    totals = usage.as_dict()
    outcome = result.get("status") or ("VALIDATED" if result.get("ok") else None)
    automation = result.get("automation") or {}

    return {
        "client_run_id": str(uuid.uuid4()),
        "cvelab_version": __version__,
        "cve": result.get("cve") or lab_dir.name,
        "repo": plan.get("repository"),
        "fixed_ref": revisions.get("patched"),
        "provider": provider,
        "model": model or (totals["models"][0] if totals["models"] else None),
        "status": STATUS.get(outcome or "", "failed"),
        "outcome": outcome,
        "attempts": automation.get("validation_attempts"),
        "input_tokens": totals["input_tokens"],
        "output_tokens": totals["output_tokens"],
        "cost_usd": totals["estimated_cost_usd"],
        "error": (
            strip_local_paths(redact(str(result["error"])), lab_dir)[:4000]
            if result.get("error")
            else None
        ),
        "documents": documents,
        "dropped_documents": dropped,
    }


def fit_payload(documents: list[dict]) -> tuple[list[dict], list[str]]:
    """Trim to what the control plane will accept, least useful first.

    What sharing requires is kept first, then the rest in ALWAYS order, so
    the analysis goes before anything the corpus gate checks. The kept
    documents stay in their original order.
    """
    total = sum(len(d["text"].encode("utf-8")) for d in documents)
    if total <= MAX_PAYLOAD_BYTES:
        return documents, []
    priority = sorted(documents, key=lambda d: d["name"] not in REQUIRED_TO_SHARE)
    kept_names, dropped, used = set(), [], 0
    for document in priority:
        size = len(document["text"].encode("utf-8"))
        if used + size <= MAX_PAYLOAD_BYTES:
            kept_names.add(document["name"])
            used += size
        else:
            dropped.append(document["name"])
    return [d for d in documents if d["name"] in kept_names], dropped


def describe(payload: dict) -> str:
    """What is about to be sent, before it is sent."""
    lines = [
        f"uploading {payload['cve']} to {endpoint()}",
        f"  status      {payload['status']} ({payload['outcome'] or 'unknown'})",
    ]
    for document in payload["documents"]:
        size = len(document["text"].encode("utf-8"))
        mark = " (truncated)" if document["truncated"] else ""
        lines.append(f"  {document['name']:<16}{size:>8,} bytes{mark}")
    if not payload["documents"]:
        lines.append("  (no documents; metadata only)")
    if payload.get("dropped_documents"):
        lines.append(
            "  too large for one upload, left out: "
            + ", ".join(payload["dropped_documents"])
        )
    lines.append("  the provider key is not part of this payload")
    if payload["status"] == "succeeded":
        # Saying this once per run is the difference between a corpus people
        # chose to join and one they were enrolled in.
        lines.append(
            "  a validated run joins the shared database under your account, "
            "listed as awaiting review; subscribers can open it once it is reviewed"
        )
        missing = [name for name in REQUIRED_TO_SHARE if name not in
                   {d["name"] for d in payload["documents"]}]
        exploit_sent = any(d["name"] in ("PoC.py", "manual.sh") for d in payload["documents"])
        if missing and exploit_sent:
            # Said before sending: the control plane will refuse it, and a
            # reason up front beats a 422 after the upload.
            lines.append("  missing what sharing requires, so it will be refused: " + ", ".join(missing))
        exploit = [d["name"] for d in payload["documents"] if d["name"] in EXPLOIT]
        if exploit:
            lines.append(
                "  the exploit is included: " + ", ".join(exploit)
                + " (--no-poc to withhold)"
            )
        else:
            # What this line used to say was "the entry will not be
            # runnable", and the entry carried the route, the payload in
            # prose, the canary and the raw observations of both builds. It
            # says what was done now, and stops short of what it cannot
            # promise.
            sent = sorted(d["name"] for d in payload["documents"])
            lines.append(
                "  the exploit, the plan and the reproduction steps are withheld; "
                + ", ".join(sent) + " filed with the attack redacted out of them"
            )
            lines.append(
                "  that is not the same as nobody being able to reproduce it: the "
                "repository, the fix commit and the CVE are in there"
            )
    return "\n".join(lines)


def send(payload: dict, token: str, *, timeout: int = 30) -> dict:
    refusal = insecure_endpoint()
    if refusal:
        raise UploadError(refusal)
    body = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        f"{endpoint()}/api/runs",
        data=body,
        method="POST",
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "User-Agent": f"cvelab/{__version__}",
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as error:
        raw = error.read().decode("utf-8", "replace")
        try:
            answer = json.loads(raw)
        except ValueError:
            answer = {}
        if not isinstance(answer, dict):
            answer = {}
        if error.code in (401, 403):
            raise UploadError(
                f"The control plane rejected the token ({error.code}). "
                f"Create a new one at {endpoint()}/app/ and set {TOKEN_VARIABLE}."
            ) from error
        if error.code == 422:
            failures = [str(f) for f in answer.get("failures") or []]
            raise UploadError(
                "The control plane refused the run: a validated run must carry the "
                "artifacts CVELab generates, and these checks failed:\n"
                + "\n".join(f"  - {failure}" for failure in failures),
                failures=failures,
            ) from error
        if error.code == 429:
            retry = _retry_after(error.headers.get("Retry-After"), answer.get("retry_after"))
            wait = f" Try again in {_duration(retry)}." if retry else ""
            raise UploadError(
                f"Rate limited: {answer.get('error') or 'too many uploads'}.{wait}",
                retry_after=retry,
            ) from error
        detail = answer.get("error") or raw[:600]
        raise UploadError(f"Upload failed with HTTP {error.code}: {detail}") from error
    except urllib.error.URLError as error:
        raise UploadError(f"Could not reach {endpoint()}: {error.reason}") from error


def _retry_after(header: str | None, body: object) -> int | None:
    for value in (header, body):
        try:
            seconds = int(str(value))
        except (TypeError, ValueError):
            continue
        if seconds > 0:
            return seconds
    return None


def _duration(seconds: int) -> str:
    if seconds < 120:
        return f"{seconds} seconds"
    if seconds < 7200:
        return f"{round(seconds / 60)} minutes"
    return f"{round(seconds / 3600)} hours"


def sharing(answer: dict) -> str | None:
    """One line on whether a filed run joined the shared database, or why not."""
    if answer.get("shared") is True:
        return "shared: listed as awaiting review; subscribers can open it once it is reviewed"
    reason = answer.get("not_shared")
    if reason:
        return NOT_SHARED.get(reason, f"kept private: {reason}")
    return None


def upload_result(
    lab_dir: Path,
    result: dict,
    *,
    provider: str | None = None,
    model: str | None = None,
    include_poc: bool = True,
    token: str | None = None,
) -> dict | None:
    """Upload a finished run. Returns None when no token is configured.

    A failed upload never fails the run: the lab is on disk and `cvelab
    upload <CVE>` sends it later. Losing a validated lab because a network
    was down would be a worse outcome than an unsynced report.
    """
    token = token or find_token()
    if not token:
        return None
    payload = collect(
        lab_dir, result, provider=provider, model=model, include_poc=include_poc
    )
    progress.step(describe(payload))
    try:
        answer = send(payload, token)
    except UploadError as error:
        progress.step(f"upload failed: {error}")
        progress.step(f"the lab is kept at {lab_dir}; retry with 'cvelab upload {payload['cve']}'")
        return {"ok": False, "error": str(error)}
    if answer.get("url"):
        progress.step(f"stored at {answer['url']}")
    note = sharing(answer)
    if note:
        progress.step(note)
    return answer
