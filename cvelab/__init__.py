"""CVELab: local-only CVE reproduction and PoC generation."""

from importlib.metadata import PackageNotFoundError, version

try:
    __version__ = version("cvelab")
except PackageNotFoundError:
    try:
        # cvelab.pyz has no dist-info for importlib.metadata to read, so the
        # builder stamps the version in. Without this a downloaded archive
        # reports 0.0.0+unknown in its User-Agent and in every upload.
        # Generated by scripts/build_pyz.py, so it is absent from the
        # source tree a type checker sees.
        from ._version import __version__  # type: ignore[no-redef,import-not-found]
    except ImportError:  # a source tree that was never installed or built
        __version__ = "0.0.0+unknown"

__all__ = ["__version__"]
